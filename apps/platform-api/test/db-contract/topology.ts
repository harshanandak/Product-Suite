const MANIFEST_BY_ID = new Map(SUITE_MANIFEST.map((entry) => [entry.id, entry]))

/** Classify an already-normalized manifest id. Unknown ids are hard failures. */
export function classifyTestId(id: string): TopologyEntry | undefined {
  return MANIFEST_BY_ID.get(id)
}

/** Resolve a Vitest file + exact title through the explicit manifest. */
export function resolveTestId(fileName: string, title: string): TopologyEntry | undefined {
  const suiteId = fileName
    .replaceAll('\\', '/')
    .split('/')
    .pop()
    ?.replace(/\.test\.tsx?$/, '')
  if (!suiteId || !Object.values(SUITE_IDS).includes(suiteId as SuiteId)) return undefined
  return SUITE_MANIFEST.find((entry) => entry.suiteId === suiteId && entry.title === title)
}

export interface TopologySummary {
  readonly totalAssertions: number
  readonly realAssertions: number
  readonly controlPlaneAssertions: number
  readonly transactionalAssertions: number
  readonly dedicatedAssertions: number
  readonly controlPlaneBySuite: {
    readonly 'neon-authority': number
    readonly 'role-privileges': number
    readonly reap: number
  }
}

export function getTopologySummary(manifest: readonly TopologyEntry[] = SUITE_MANIFEST): TopologySummary {
  const transactionalAssertions = manifest.filter(
    (entry) => entry.executionClass === EXECUTION_CLASSES.TRANSACTIONAL,
  ).length
  const dedicatedAssertions = manifest.filter(
    (entry) => entry.executionClass === EXECUTION_CLASSES.DEDICATED,
  ).length
  const controlPlaneAssertions = manifest.filter(
    (entry) => entry.executionClass === EXECUTION_CLASSES.CONTROL_PLANE,
  ).length
  const controlPlaneBySuite = {
    'neon-authority': manifest.filter(
      (entry) => entry.executionClass === EXECUTION_CLASSES.CONTROL_PLANE && entry.suiteId === SUITE_IDS.NEON_AUTHORITY,
    ).length,
    'role-privileges': manifest.filter(
      (entry) => entry.executionClass === EXECUTION_CLASSES.CONTROL_PLANE && entry.suiteId === SUITE_IDS.ROLE_PRIVILEGES,
    ).length,
    reap: manifest.filter(
      (entry) => entry.executionClass === EXECUTION_CLASSES.CONTROL_PLANE && entry.suiteId === SUITE_IDS.REAP,
    ).length,
  } as const

  return {
    totalAssertions: manifest.length,
    realAssertions: transactionalAssertions + dedicatedAssertions,
    controlPlaneAssertions,
    transactionalAssertions,
    dedicatedAssertions,
    controlPlaneBySuite,
  }
}
