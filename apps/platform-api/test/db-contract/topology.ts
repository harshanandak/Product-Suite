/**
 * Explicit, count-locked inventory for the real DB Contract tier.
 *
 * This is intentionally a manifest, not a file-name/prefix convention. A test
 * that is added to one of the files below must be added here before it can be
 * reported as contract evidence. Ambiguous work is therefore fail-closed.
 */

export const TOPOLOGY_VERSION = 'db-contract-v1' as const

export const EXECUTION_CLASSES = {
  TRANSACTIONAL: 'transactional-suite',
  DEDICATED: 'dedicated-branch',
  CONTROL_PLANE: 'control-plane-unit',
} as const

export type ExecutionClass = (typeof EXECUTION_CLASSES)[keyof typeof EXECUTION_CLASSES]

export const SUITE_IDS = {
  ACCEPT_PATH: 'accept-path',
  BASELINE: 'baseline',
  COLLABORATION: 'collaboration',
  MEETING_INGEST: 'meeting-ingest',
  MEMORY_CURATOR: 'memory-curator',
  MEMORY_TIER: 'memory-tier',
  NEON_AUTHORITY: 'neon-authority',
  ROLE_PRIVILEGES: 'role-privileges',
  REAP: 'reap',
} as const

export type SuiteId = (typeof SUITE_IDS)[keyof typeof SUITE_IDS]

export interface TopologyEntry {
  readonly id: string
  readonly suiteId: SuiteId
  readonly executionClass: ExecutionClass
  /** A control-plane/unit assertion is never branch coverage. */
  readonly branchCoverage: boolean
  /** Exact Vitest title when the test is not generated by a table. */
  readonly title?: string
}

const transactional = (suiteId: SuiteId, id: string, title: string): TopologyEntry => ({
  id,
  suiteId,
  executionClass: EXECUTION_CLASSES.TRANSACTIONAL,
  branchCoverage: true,
  title,
})

const dedicated = (suiteId: SuiteId, id: string, title: string): TopologyEntry => ({
  id,
  suiteId,
  executionClass: EXECUTION_CLASSES.DEDICATED,
  branchCoverage: true,
  title,
})

const controlPlane = (suiteId: SuiteId, id: string, title: string): TopologyEntry => ({
  id,
  suiteId,
  executionClass: EXECUTION_CLASSES.CONTROL_PLANE,
  branchCoverage: false,
  title,
})

